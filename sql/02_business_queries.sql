USE tec_project;

/*QWERY #1 */

SELECT 
    c.COURSE_NUM,
    c.COURSE_DESCRIPTION,
    COUNT(p.QUAL_CODE) AS Num_Prerequisites
FROM COURSE c
LEFT JOIN PREREQUISITE p 
    ON c.COURSE_NUM = p.COURSE_NUM
GROUP BY 
    c.COURSE_NUM, 
    c.COURSE_DESCRIPTION
ORDER BY 
    c.COURSE_NUM;

/*QWERY #2 */

SELECT 
    c.COURSE_NUM,
    c.COURSE_DESCRIPTION,
    COUNT(s.SESSION_NUM) AS Num_Sessions
FROM COURSE c
JOIN SESSION s
    ON c.COURSE_NUM = s.COURSE_NUM
GROUP BY
    c.COURSE_NUM,
    c.COURSE_DESCRIPTION
ORDER BY
    c.COURSE_NUM;

/*QWERY #3 */
SELECT 
    j.JH_ID,
    j.CAND_NUM,
    p.PLACEMENT_NUM,
    p.PLACEMENT_DATE,
    p.PLACEMENT_TOTALHOURS,
    o.OPENING_DESCRIPTION,
    o.COMP_CODE
FROM JOBHISTORY j
JOIN PLACEMENT p 
    ON j.PLACEMENT_NUM = p.PLACEMENT_NUM
JOIN OPENING o
    ON p.OPENING_NUM = o.OPENING_NUM
WHERE j.CAND_NUM = 'C001';

/* Querey #4 */
SELECT 
    o.QUAL_CODE,
    q.QUAL_DESCRIPTION,
    o.COMP_CODE,
    c.COMP_NAME,
    COUNT(o.OPENING_NUM) AS Num_Openings
FROM OPENING o
JOIN COMPANY c 
    ON o.COMP_CODE = c.COMP_CODE
JOIN QUALIFICATION q
    ON o.QUAL_CODE = q.QUAL_CODE
WHERE o.QUAL_CODE = 'QUAL010'  
GROUP BY
    o.QUAL_CODE,
    q.QUAL_DESCRIPTION,
    o.COMP_CODE,
    c.COMP_NAME
ORDER BY
    Num_Openings DESC;
    
/* Query #5 */ 
SELECT 
    p.CAND_NUM,
    c.CAND_LNAME,
    o.COMP_CODE,
    COUNT(p.PLACEMENT_NUM) AS NUM_PLACEMENTS
FROM PLACEMENT p
JOIN OPENING o 
    ON p.OPENING_NUM = o.OPENING_NUM
JOIN CANDIDATE c 
    ON p.CAND_NUM = c.CAND_NUM
WHERE o.COMP_CODE = 'COMP001'    
GROUP BY 
    p.CAND_NUM,
    c.CAND_LNAME,
    o.COMP_CODE
ORDER BY 
    NUM_PLACEMENTS DESC;
    
    /* Query #6 */ 
    SELECT 
    c.COURSE_NUM,
    c.COURSE_DESCRIPTION,
    SUM(e.ENROLL_FEEPAID) AS Total_Revenue
FROM COURSE c
JOIN SESSION s 
    ON c.COURSE_NUM = s.COURSE_NUM
JOIN ENROLL e
    ON s.SESSION_NUM = e.SESSION_NUM
GROUP BY 
    c.COURSE_NUM,
    c.COURSE_DESCRIPTION
ORDER BY 
    Total_Revenue DESC;
    
    /* Query #7*/

SELECT 
    q.QUAL_CODE,
    q.QUAL_DESCRIPTION,
    COUNT(e.CAND_NUM) AS Num_Candidates
FROM QUALIFICATION q
JOIN EDUCATION e
    ON q.QUAL_CODE = e.QUAL_CODE
GROUP BY 
    q.QUAL_CODE,
    q.QUAL_DESCRIPTION
ORDER BY 
    Num_Candidates DESC;
    
     /* Query #8*/
     
    SELECT
    c.COMP_NAME,
    COUNT(o.OPENING_NUM) AS TOTAL_AVAILABLE_OPENINGS
FROM COMPANY c
JOIN OPENING o
    ON c.COMP_CODE = o.COMP_CODE
WHERE o.OPENING_AVAILABLE = 'YES'
GROUP BY
    c.COMP_NAME
ORDER BY
    TOTAL_AVAILABLE_OPENINGS DESC;
  /* Query #9*/
SELECT
    p.CAND_NUM,
    c.CAND_LNAME,
    o.COMP_CODE,
    COUNT(p.PLACEMENT_NUM) AS NUM_PLACEMENTS
FROM PLACEMENT p
JOIN OPENING o
    ON p.OPENING_NUM = o.OPENING_NUM
JOIN CANDIDATE c
    ON p.CAND_NUM = c.CAND_NUM
WHERE o.COMP_CODE = 'COMP005' 
GROUP BY
    p.CAND_NUM,
    c.CAND_LNAME,
    o.COMP_CODE
ORDER BY
    NUM_PLACEMENTS DESC;
/* Query #10*/

SELECT
    c.CAND_NUM,
    c.CAND_LNAME,
    COUNT(e.QUAL_CODE) AS TOTAL_QUALIFICATIONS
FROM CANDIDATE c
JOIN EDUCATION e
    ON c.CAND_NUM = e.CAND_NUM
GROUP BY
    c.CAND_NUM,
    c.CAND_LNAME
ORDER BY
    TOTAL_QUALIFICATIONS DESC;

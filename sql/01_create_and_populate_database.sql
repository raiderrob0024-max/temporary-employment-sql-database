/*  TEC PROJECT DATABASE  */

-- Drop the database if it already exists
DROP DATABASE IF EXISTS tec_project;

-- Create the database
CREATE DATABASE tec_project;

-- Select the database
USE tec_project;

/*COMPANY*/

CREATE TABLE COMPANY (
    COMP_CODE      VARCHAR(10) PRIMARY KEY,
    COMP_NAME      VARCHAR(100) NOT NULL
);


/*QUALIFICATION*/

CREATE TABLE QUALIFICATION (
    QUAL_CODE        VARCHAR(10) PRIMARY KEY,
    QUAL_DESCRIPTION VARCHAR(255)
);

/*COURSE*/

CREATE TABLE COURSE (
    COURSE_NUM         VARCHAR(10) PRIMARY KEY,
    COURSE_DESCRIPTION VARCHAR(255),
    COURSE_FEE         DECIMAL(10,2),
    QUAL_CODE          VARCHAR(10),
    FOREIGN KEY (QUAL_CODE) REFERENCES QUALIFICATION(QUAL_CODE)
);

/*SESSION*/

CREATE TABLE SESSION (
    SESSION_NUM       VARCHAR(10) PRIMARY KEY,
    SESSION_STARTDATE DATE,
    SESSION_FEE       DECIMAL(10,2),
    COURSE_NUM        VARCHAR(10),
    FOREIGN KEY (COURSE_NUM) REFERENCES COURSE(COURSE_NUM)
);

/*CANDIDATE*/

CREATE TABLE CANDIDATE (
    CAND_NUM    VARCHAR(10) PRIMARY KEY,
    CAND_LNAME  VARCHAR(100) NOT NULL
);

/*OPENING*/

CREATE TABLE OPENING (
    OPENING_NUM         VARCHAR(10) PRIMARY KEY,
    OPENING_DESCRIPTION VARCHAR(255),
    OPENING_AVAILABLE   VARCHAR(5),
    COMP_CODE           VARCHAR(10),
    QUAL_CODE           VARCHAR(10),
    FOREIGN KEY (COMP_CODE) REFERENCES COMPANY(COMP_CODE),
    FOREIGN KEY (QUAL_CODE) REFERENCES QUALIFICATION(QUAL_CODE)
);

/*PLACEMENT*/

CREATE TABLE PLACEMENT (
    PLACEMENT_NUM        VARCHAR(10) PRIMARY KEY,
    PLACEMENT_DATE       DATE,
    PLACEMENT_TOTALHOURS INT,
    OPENING_NUM          VARCHAR(10),
    CAND_NUM             VARCHAR(10),
    FOREIGN KEY (OPENING_NUM) REFERENCES OPENING(OPENING_NUM),
    FOREIGN KEY (CAND_NUM) REFERENCES CANDIDATE(CAND_NUM)
);

/*JOBHISTORY*/

CREATE TABLE JOBHISTORY (
    JH_ID          VARCHAR(10) PRIMARY KEY,
    CAND_NUM       VARCHAR(10),
    PLACEMENT_NUM  VARCHAR(10),
    FOREIGN KEY (CAND_NUM) REFERENCES CANDIDATE(CAND_NUM),
    FOREIGN KEY (PLACEMENT_NUM) REFERENCES PLACEMENT(PLACEMENT_NUM)
);


/*ENROLL*/

CREATE TABLE ENROLL (
    SESSION_NUM     VARCHAR(10),
    CAND_NUM        VARCHAR(10),
    ENROLL_DATE     DATE,
    ENROLL_FEEPAID  DECIMAL(10,2),
    PRIMARY KEY (SESSION_NUM, CAND_NUM),
    FOREIGN KEY (SESSION_NUM) REFERENCES SESSION(SESSION_NUM),
    FOREIGN KEY (CAND_NUM) REFERENCES CANDIDATE(CAND_NUM)
);


/*EDUCATION*/

CREATE TABLE EDUCATION (
    QUAL_CODE   VARCHAR(10),
    CAND_NUM    VARCHAR(10),
    EDUC_DATE   DATE,
    PRIMARY KEY (QUAL_CODE, CAND_NUM),
    FOREIGN KEY (QUAL_CODE) REFERENCES QUALIFICATION(QUAL_CODE),
    FOREIGN KEY (CAND_NUM) REFERENCES CANDIDATE(CAND_NUM)
);

/*PREREQUISITE*/

CREATE TABLE PREREQUISITE (
    QUAL_CODE    VARCHAR(10),
    COURSE_NUM   VARCHAR(10),
    PRIMARY KEY (QUAL_CODE, COURSE_NUM),
    FOREIGN KEY (QUAL_CODE) REFERENCES QUALIFICATION(QUAL_CODE),
    FOREIGN KEY (COURSE_NUM) REFERENCES COURSE(COURSE_NUM)
);

/* EMPLOYEE */

CREATE TABLE EMPLOYEE (
    EMPLOYEE_ID   VARCHAR(10) PRIMARY KEY,
    COMP_CODE     VARCHAR(10),
    FIRST_NAME    VARCHAR(100),
    LAST_NAME     VARCHAR(100),
    ROLE          VARCHAR(100),
    EMAIL         VARCHAR(255),
    FOREIGN KEY (COMP_CODE) REFERENCES COMPANY(COMP_CODE)
);
